function getSessionStorage() {
  try {
    return globalThis.sessionStorage;
  } catch {
    return null;
  }
}

function storageKey(lang) {
  return `keyprint_sentence_deck_v1_${lang}`;
}

function restoreDeck(storage, lang) {
  try {
    const stored = JSON.parse(storage?.getItem(storageKey(lang)) ?? 'null');
    const pool = SENTENCE_POOLS[lang];
    const lastPicked = pool.includes(stored?.lastPicked) ? stored.lastPicked : '';
    const queue = stored?.queue;
    const validQueue =
      Boolean(lastPicked) &&
      Array.isArray(queue) &&
      new Set(queue).size === queue.length &&
      queue.every((sentence) => sentence !== lastPicked && pool.includes(sentence));
    return { queue: validQueue ? queue : [], lastPicked };
  } catch {
    return { queue: [], lastPicked: '' };
  }
}

export class SentenceDeck {
  constructor(storage = getSessionStorage()) {
    this.storage = storage;
    this.decks = Object.fromEntries(
      Object.keys(SENTENCE_POOLS).map((lang) => [lang, restoreDeck(storage, lang)])
    );
  }

  next(lang = 'ko') {
    const key = lang === 'en' ? 'en' : 'ko';
    const deck = this.decks[key];
    if (deck.queue.length === 0) {
      const copy = [...SENTENCE_POOLS[key]];
      for (let i = copy.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [copy[i], copy[j]] = [copy[j], copy[i]];
      }
      if (copy.length > 1 && copy[0] === deck.lastPicked) {
        const replacement = 1 + Math.floor(Math.random() * (copy.length - 1));
        [copy[0], copy[replacement]] = [copy[replacement], copy[0]];
      }
      deck.queue = copy;
    }
    deck.lastPicked = deck.queue.shift();
    try {
      this.storage?.setItem(storageKey(key), JSON.stringify(deck));
    } catch {
      // Keep dealing from memory when browser storage is unavailable.
    }
    return deck.lastPicked;
  }
}
