/** Functional state transitions with in-memory storage and a mocked broker; no external traffic. */
import assert from 'node:assert/strict';
import { ActionGate } from '../src/asyncActions.js';
import { RoomProfileSync } from '../src/roomSync.js';

const gate = new ActionGate();
let release;
const pending = new Promise((resolve) => { release = resolve; });
let applied = 0;
const first = gate.run(async (isCurrent) => { await pending; if (isCurrent()) applied += 1; });
assert.equal(await gate.run(async () => { applied += 1; }), false);
gate.invalidate();
release();
await first;
assert.equal(applied, 0, 'Changing workspace discards the previous asynchronous result');
await gate.run(async (isCurrent) => { if (isCurrent()) applied += 1; });
assert.equal(applied, 1);
await assert.rejects(gate.run(async () => { throw new Error('simulated inference failure'); }));
assert.equal(gate.pending, false, 'An inference error releases the submission gate');

const storage = new Map();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: k => storage.get(k) || null, setItem: (k, v) => storage.set(k, v) }, configurable: true });
const originalChannel = globalThis.BroadcastChannel;
globalThis.BroadcastChannel = undefined;
const compat = { schemaVersion: 4, preprocessVersion: 'kp-preproc-v4', modelHash: 'functional-fixture' };
const vec = Array.from({ length: 64 }, (_, i) => i === 0 ? 1 : 0);
const profile = (id) => ({ id, name: id, isSample: false, color: '#2563eb', arena: { en: { centroid: vec, exemplars: [vec], count: 1, inputMode: 'keyboard' } } });
const sync = new RoomProfileSync(compat);
let connections = 0;
sync._connectMqtt = () => { connections += 1; };
sync.connect('INVITED');
assert.equal(connections, 0);
assert.equal(sync.shared, false);
sync.upsertProfile(profile('local_person'));
sync.connect('TEAM', { shared: true });
assert.equal(connections, 1);
assert.equal(sync.getProfiles().length, 0, 'Local profiles are not copied into a shared room');
const published = [];
sync.client = { connected: true, publish(topic, payload, options, cb) { published.push({ topic, payload, options }); cb?.(); }, end() {} };
const p = sync.upsertProfile(profile('shared_person'));
assert.equal(sync.pendingUpdates.size, 0);
assert.ok(published.some(x => x.topic.endsWith('/profiles/shared_person') && x.options.retain));
sync.client.connected = false;
const newer = sync.upsertProfile({ ...p, arena: { en: { ...p.arena.en, count: 2 } } });
assert.ok(sync.pendingUpdates.has(p.id), 'Offline edits remain queued');
sync._applyDelete(p.id, p.updatedAt);
assert.equal(sync.getProfiles()[0].arena.en.count, 2, 'A stale delete cannot remove a newer profile');
sync._applyDelete(p.id, newer.updatedAt + 1);
assert.equal(sync.getProfiles().length, 0);
assert.equal(sync.pendingUpdates.size, 0);
assert.equal(sync._mergeIncomingProfile(p), false, 'A cached older profile cannot resurrect a deletion');
assert.equal(sync._mergeIncomingProfile({ ...newer, updatedAt: newer.updatedAt + 2 }), true, 'A genuinely newer update remains usable');
sync.deleteProfile(p.id); // Offline delete is persisted, including its timestamp.
const reload = new RoomProfileSync(compat);
reload._connectMqtt = () => {};
reload.connect('TEAM', { shared: true });
assert.equal(reload.getProfiles().length, 0);
assert.ok(reload.tombstones.has(p.id));
reload.client = { connected: true, publish(topic, payload, options, cb) { published.push({ topic, payload, options }); cb?.(); }, end() {} };
for (const [id, ts] of reload.tombstones) reload._publishDeletion(id, ts);
assert.ok(published.some(x => x.topic.includes('/deletions/shared_person/') && x.options.retain));
sync.connect('LOCAL');
assert.deepEqual(sync.getProfiles().map(x => x.id), ['local_person']);
sync.disconnect(); reload.disconnect();
globalThis.BroadcastChannel = originalChannel;
console.log('Functional state transitions passed: local consent/isolation, pending submissions, errors, offline updates/deletes, retained tombstones and timestamp ordering.');
